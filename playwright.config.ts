import { defineConfig } from '@playwright/test';

/**
 * End-to-end tests: they run against the final `dist/index.html` (`npm run build`),
 * served locally. CI only (see .github/workflows/ci.yml); the Claude Code cloud
 * environment may not have the browser. To run outside CI, point to an already
 * installed Chromium with `PLAYWRIGHT_CHROMIUM_EXECUTABLE=/path/to/chrome`.
 */
const executablePath = process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE || undefined;
const PORT = 4173;

export default defineConfig({
  testDir: 'tests/e2e',
  testMatch: '**/*.spec.ts',
  fullyParallel: true,
  forbidOnly: Boolean(process.env.CI),
  // CI uses 3 workers (the default is half the cores); locally, the default.
  workers: process.env.CI ? 3 : undefined,
  // One retry in CI, with a trace only on it (the first failure stays in the report).
  retries: process.env.CI ? 1 : 0,
  reporter: process.env.CI ? [['list'], ['html', { open: 'never' }]] : 'list',
  use: {
    baseURL: `http://localhost:${PORT}`,
    locale: 'en-US',
    trace: 'on-first-retry',
    launchOptions: { executablePath },
  },
  projects: [
    {
      name: 'desktop',
      use: { viewport: { width: 1280, height: 860 } },
    },
  ],
  webServer: {
    // Serves the dist/ generated by the build (CI already generated it before).
    command: `npx vite preview --port ${PORT} --strictPort`,
    url: `http://localhost:${PORT}`,
    reuseExistingServer: !process.env.CI,
  },
});
